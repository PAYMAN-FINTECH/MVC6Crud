    class AES_ENCRYPTION
    {
        // Initialization Vector length for the AES encryption.
        private int ivLength;
        // The cipher algorithm used for encryption.
        private string cipherAlgo;
        // The secret key used for AES encryption.
        private byte[] secretKey;


        // Constructor for AES_ENCRYPTION class that takes the base64 encoded secret key.
        public AES_ENCRYPTION(string base64SecretKey)
        {
            // 128 bits or 16 bytes is the initialization vector length.
            ivLength = 16;
            // 256 bits is key size.
            cipherAlgo = "AES";
            // 256 bits secret_key encoded in base64_decode expected
            secretKey = Convert.FromBase64String(base64SecretKey);
        }

        // Method to encrypt the given string data using AES encryption.
        public string Encrypt(string data)
        {
            // initialization vector
            byte[] iv = new byte[ivLength];
            Random random = new Random();
            random.NextBytes(iv);
            using (Aes aes = Aes.Create())
            {
                aes.Key = secretKey;
                aes.IV = iv;
                aes.Mode = CipherMode.CBC;
                aes.Padding = PaddingMode.PKCS7;

                ICryptoTransform encryptor = aes.CreateEncryptor(aes.Key, aes.IV);

                byte[] rawData = Encoding.UTF8.GetBytes(data);
                byte[] encryptedData = encryptor.TransformFinalBlock(rawData, 0, rawData.Length);

                string encryptedBase64 = Convert.ToBase64String(iv.Concat(encryptedData).ToArray());

                return encryptedBase64;
            }
        }
    }

