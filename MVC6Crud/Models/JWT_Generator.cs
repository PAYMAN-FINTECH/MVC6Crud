        // Method to construct the payload for the JWT token.
        public Dictionary<string, object> GetPayload()
        {
            AES_ENCRYPTION encryptor = new AES_ENCRYPTION(secret);
            string data = JsonSerializer.Serialize(new { mid = mid, iss = iss, agr = aggr });
            string encryptedData = encryptor.Encrypt(data);

            Dictionary<string, object> claims = new Dictionary<string, object>
        {
            { "data", encryptedData },
            { "srv", "Payout" },
            { "sub", Convert.ToBase64String(Encoding.UTF8.GetBytes(user_ref_id)) }
        };
            return claims;
        }

        // Method to generate the JWT token with the given payload and sign it with RSA private key.
        public string GenerateToken()
        {
            var claims = GetPayload();

            RsaSecurityKey rsaKey = CreateRsaSecurityKeyFromPem(privateKey);

            var tokenHandler = new JwtSecurityTokenHandler();
            var tokenDescriptor = new SecurityTokenDescriptor
            {
                Audience = "Plural",
                Claims = claims,
                IssuedAt = DateTime.UtcNow,
                Expires = DateTime.UtcNow.AddMinutes(30), // Token expiry set to 30 minutes
                SigningCredentials = new SigningCredentials(rsaKey, SecurityAlgorithms.RsaSha256)
            };

            var token = tokenHandler.CreateToken(tokenDescriptor);
            return tokenHandler.WriteToken(token);

        }

        public static RsaSecurityKey CreateRsaSecurityKeyFromPem(string pemString)
        {
            RSA rsa = CreateRsaProviderFromPem(pemString);
            return new RsaSecurityKey(rsa);
        }

        private static RSA CreateRsaProviderFromPem(string pemString)
        {
            using (StringReader stringReader = new StringReader(pemString))
            {
                PemReader pemReader = new PemReader(stringReader);
                object pemObject = pemReader.ReadObject();
                if (pemObject is RsaPrivateCrtKeyParameters parameters)
                {
                    RSAParameters rsaParameters = DotNetUtilities.ToRSAParameters(parameters);
                    RSA rsa = RSA.Create();
                    rsa.ImportParameters(rsaParameters);
                    return rsa;
                }
                else
                {
                    throw new Exception("Unsupported PEM object was found.");
                }
            }
        }
